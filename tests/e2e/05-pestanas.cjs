// EarlyStock 2.4: pestañas del panel, atajos, navegación desde sugerencias/alertas, inicio, ventanas y celular.
const { abrir, estado, USER } = require('./simulado.cjs')
const OUT = require('path').join(__dirname, '..', '..', 'test-results', 'e2e')
require('fs').mkdirSync(OUT, { recursive: true })
const ok = (c, m) => { if (!c) throw new Error('FALLÓ: ' + m); console.log('  ✓ ' + m) }
const activa = pg => pg.getAttribute('.pestanas-panel .pestana.activa', 'data-pestana')
const pantallas = pg => pg.evaluate(() => +(document.documentElement.scrollHeight / innerHeight).toFixed(1))
;(async () => {
  USER.user_metadata = { acepto_politicas: '2026-11b', negocio: 'Abarrotes Don Pepe' }
  const { b, pg, errs } = await abrir()
  await pg.addInitScript(() => localStorage.setItem('earlystock.guia', '1'))
  console.log('Página de inicio')
  await pg.goto('https://app.test/ITDHackaton2026/'); await pg.waitForSelector('#conoce')
  ok(await pg.isVisible('#como') && !(await pg.isVisible('#seguridad')), '"Conoce EarlyStock" muestra una pestaña a la vez')
  await pg.click('.nav-links >> text=Seguridad'); await pg.waitForTimeout(400)
  ok(await pg.isVisible('#seguridad'), 'el menú "Seguridad" abre su pestaña')
  await pg.locator('#conoce').screenshot({ path: OUT + '/t-inicio.png' })

  console.log('Panel con pestañas')
  await pg.click('.nav-der >> text=Entrar')
  await pg.fill('.form-acceso input[type=email]', 'dueno@tienda.mx'); await pg.fill('.form-acceso .campo-clave input', 'tienda2026')
  await pg.click('.form-acceso button[type=submit]'); await pg.waitForSelector('.pestanas-panel')
  await pg.click('text=Probar con una tienda de ejemplo'); await pg.waitForSelector('#aviso:has-text("cargada")'); await pg.waitForTimeout(800)
  ok(await activa(pg) === 'hoy', 'empieza en Hoy')
  const alto = await pantallas(pg); ok(alto <= 1.5, `Hoy cabe en ${alto} pantallas (antes ~5)`)
  await pg.screenshot({ path: OUT + '/t-hoy.png' })
  for (const [k, id] of [['2', 'inventario'], ['3', 'compras'], ['4', 'ofertas'], ['5', 'reportes'], ['6', 'mas'], ['1', 'hoy']]) { await pg.keyboard.press(k); await pg.waitForTimeout(120); ok(await activa(pg) === id, `tecla ${k} → ${id}`) }
  await pg.keyboard.press('Control+k'); await pg.fill('.cmd-buscar input', 'ir a compras'); await pg.keyboard.press('Enter'); await pg.waitForTimeout(200)
  ok(await activa(pg) === 'compras' && await pg.isVisible('#compras'), 'Ctrl+K "Ir a Compras"')
  await pg.keyboard.press('1')
  await pg.locator('.sug', { hasText: 'Pide' }).first().locator('text=Ver lista de compras').click().catch(async () => { await pg.click('#sugerencias >> text=Ver todas'); await pg.locator('.sug', { hasText: 'Pide' }).first().locator('text=Ver lista de compras').click() })
  await pg.waitForTimeout(300); ok(await activa(pg) === 'compras', '"Ver lista de compras" cambia a la pestaña Compras')
  await pg.keyboard.press('1'); await pg.click('#alertas .fila-alerta >> nth=0'); await pg.waitForTimeout(500)
  ok(await activa(pg) === 'inventario' && await pg.locator('#inventario .variante.resaltar, #inventario .resaltar').count() > 0, 'tocar una alerta lleva al producto en Inventario y lo resalta')
  await pg.keyboard.press('1'); await pg.click('.stat:has-text("Urgentes")'); await pg.waitForTimeout(300)
  ok(await activa(pg) === 'inventario' && await pg.isVisible('.chip.activo:has-text("Urgentes")'), 'el número "Urgentes" abre Inventario filtrado')
  await pg.keyboard.press('5'); await pg.mouse.move(5, 500); await pg.waitForTimeout(1500); await pg.screenshot({ path: OUT + '/t-reportes.png' })

  console.log('Ventanas')
  await pg.click('[aria-label="Configuración"]'); await pg.waitForSelector('dialog .plegable')
  ok(await pg.locator('dialog details.plegable').count() === 3 && await pg.locator('dialog details.plegable[open]').count() === 1, 'Configuración: 3 plegables, solo "Apariencia" abierto')
  await pg.click('dialog summary:has-text("Avisos")'); ok(await pg.isVisible('dialog >> text=Avisar caducidad con'), 'abrir "Avisos"')
  await pg.keyboard.press('Escape')
  await pg.click('.btn-perfil'); await pg.click('text=Llaves de acceso, actividad y dispositivos'); await pg.waitForSelector('.pestanas-ventana')
  ok(await pg.isVisible('text=Revisión automática') && !(await pg.isVisible('text=Actividad reciente')), 'Seguridad en pestañas')
  await pg.click('[data-pestana=actividad]'); ok(await pg.isVisible('text=Actividad reciente'), 'pestaña Actividad')
  await pg.keyboard.press('Escape')
  console.log('Celular')
  await pg.setViewportSize({ width: 390, height: 844 }); await pg.keyboard.press('1'); await pg.waitForTimeout(300)
  const barra = await pg.evaluate(() => { const r = document.querySelector('.pestanas-panel').getBoundingClientRect(); return { abajo: Math.round(innerHeight - r.bottom), ancho: document.documentElement.scrollWidth } })
  ok(barra.abajo <= 1 && barra.ancho <= 390, 'barra de pestañas fija abajo y sin scroll horizontal')
  await pg.screenshot({ path: OUT + '/t-movil-hoy.png' })
  await pg.click('.pestanas-panel [data-pestana=inventario]'); await pg.waitForTimeout(300); await pg.screenshot({ path: OUT + '/t-movil-inv.png' })
  ok(!errs.filter(e => /CSP|Content Security/.test(e)).length, 'sin violaciones de CSP')
  console.log('Errores:', errs.filter(e => !/Failed to load resource/.test(e)))
  await b.close(); console.log('TODO OK')
})().catch(e => { console.error(e); process.exit(1) })
