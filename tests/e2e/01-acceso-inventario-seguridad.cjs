  await pg.click('[data-pestana=llaves]')
  await pg.click('text=Agregar llave en este dispositivo')
  await toast(pg, 'Llave de acceso agregada')
  ok(await pg.isVisible('.llaves >> text=/Llave de Chrome/'), 'llave registrada con autenticador virtual y renombrada')
  await pg.screenshot({ path: OUT + '/e-seguridad.png' })
