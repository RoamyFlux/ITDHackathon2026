  await claves.nth(0).fill('12345678')
  await claves.nth(1).fill('12345678')
  await f.locator('input[type=checkbox]').check()
  ok(await f.locator('button[type=submit]').isDisabled(), 'contraseña solo números: botón deshabilitado')
  await claves.nth(0).fill('tienda2026'); await claves.nth(1).fill('tienda2026')
