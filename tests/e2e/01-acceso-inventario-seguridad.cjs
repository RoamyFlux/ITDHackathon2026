  await pg.screenshot({ path: OUT + '/e-notif.png' })
  await pg.keyboard.press('Escape')
  // Tabla y filtro
  await tab(pg, 'inventario')
  await pg.click('text=Tabla'); await pg.waitForSelector('.tabla')
