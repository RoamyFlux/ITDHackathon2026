  await pg.screenshot({ path: OUT + '/e-revisa.png' })

  console.log('Entrar')
  await pg.click('text=Ya lo confirmé: entrar')
  await f.locator('input[type=email]').fill('dueno@tienda.mx')
  for (let i = 0; i < 3; i++) { await f.locator('.campo-clave input').fill('mala1234'); await f.locator('button[type=submit]').click(); await pg.waitForSelector('.error-form'); await pg.waitForTimeout(150) }
  ok(await pg.isVisible('text=/Te quedan 2 intentos/'), 'avisa intentos restantes')
  await f.locator('.campo-clave input').fill('tienda2026'); await f.locator('button[type=submit]').click()
  await pg.waitForSelector('text=Antes de continuar')
  ok(true, 'pide aceptar políticas a cuenta sin aceptación')
  await pg.check('dialog >> input[type=checkbox]'); await pg.click('text=Aceptar y continuar')
  await pg.waitForSelector('.guia', { timeout: 8000 })
  for (let i = 0; i < 5; i++) await pg.click('.guia >> text=Siguiente')
  await pg.click('text=Agregar mi primer producto')
  await pg.waitForSelector('dialog >> text=Agregar producto')
  await pg.keyboard.press('Escape')

  console.log('Inventario')
  await pg.click('text=Probar con una tienda de ejemplo')
  await toast(pg, 'Tienda de ejemplo cargada')
  ok(estado.DB.productos.length === 13, '13 presentaciones/sabores de ejemplo')
  ok(await pg.isVisible('text=Haz una oferta de Huevo · Cartón 30'), 'sugiere oferta para Huevo')
